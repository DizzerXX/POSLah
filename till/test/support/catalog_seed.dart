/// A small local catalog, as a pull-sync would have left it.
class SeededCatalog {
  const SeededCatalog({
    required this.categoryId,
    required this.beansProductId,
    required this.smallBagVariantId,
    required this.largeBagVariantId,
    required this.teeProductId,
    required this.teeVariantId,
    required this.corkageProductId,
  });

  final String categoryId;
  final String beansProductId;
  final String smallBagVariantId;
  final String largeBagVariantId;
  final String teeProductId;
  final String teeVariantId;

  /// tracks_stock: false, no variant — a sellable product that touches no inventory.
  final String corkageProductId;
}

