}

/// Opening stock, as a manual adjustment would have left it.
Future<void> seedStock(LocalDatabase db, String variantId, int units) {
  return db.into(db.stockLevels).insert(
        StockLevelsCompanion.insert(
          id: 'lvl-$variantId',
          storeId: storeId,
          stockableType: 'product_variant',
          stockableId: variantId,
          quantityOnHandMilli: Value(units * 1000),
        ),
      );
}

